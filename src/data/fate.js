// 운명의 저울: 빛/어둠 개수
export function fateTally(run, royal) {
  const list = (run.fate && run.fate[royal]) || [];
  return { light: list.filter((x) => x === 'light').length, dark: list.filter((x) => x === 'dark').length, n: list.length, last: list[list.length - 1] };
}
// 8장 모두 봤으면 결말 id, 아니면 null (동점이면 마지막 장 선택)
export function royalEnding(run, royal) {
  const t = fateTally(run, royal);
  if (t.n < FATE_CHAPTERS) return null;
  const side = t.light > t.dark ? 'light' : t.dark > t.light ? 'dark' : t.last;
  return `${royal}_${side}`;
}
